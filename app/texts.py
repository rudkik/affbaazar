# Тексты, которые были настройками и раньше: у них тот же шаблонизатор и та же проверка HTML.
LEGACY_HTML_KEYS = ("restricted_text", "welcome_message", "no_tokens_text", "bot_only_text",
                    "rules_text", "intro_note")


def defaults() -> dict[str, str]:
    return {key: item[1] for key, item in _T.items()}


def registry() -> list[dict]:
    """Описание текстов для админки: ключ, название, значение по умолчанию, переменные."""
    return [{"key": key, "label": label, "default": default, "vars": list(variables),
             "plain": plain}
            for key, (label, default, variables, plain) in _T.items()]


def is_plain(key: str) -> bool:
    return key in _T and _T[key][3]


def is_html(key: str) -> bool:
    return (key in _T and not _T[key][3]) or key in LEGACY_HTML_KEYS


# ------------------------------------------------------------------ проверка разметки
class _Checker(HTMLParser):
    def __init__(self) -> None:
        super().__init__(convert_charrefs=False)   # &lt; не должен превращаться в "<"
        self.stack: list[str] = []
        self.error: Optional[str] = None

    def handle_starttag(self, tag, attrs):
        if self.error:
            return
        if tag not in ALLOWED_TAGS:
            self.error = f"тег <{tag}> не поддерживается Telegram"
            return
        self.stack.append(tag)

    def handle_startendtag(self, tag, attrs):
        if not self.error:
            self.error = f"тег <{tag}/> не поддерживается Telegram"

    def handle_endtag(self, tag):
        if self.error:
            return
        if not self.stack or self.stack[-1] != tag:
            self.error = f"лишний или перепутанный закрывающий тег </{tag}>"
            return
        self.stack.pop()

    def handle_data(self, data):
        if not self.error and "<" in data:
            self.error = "символ < вне тега: замените его на &lt;"


def validate_html(value: str) -> Optional[str]:
    """None — разметка годится для Telegram; иначе человекочитаемая причина."""
    checker = _Checker()
    try:
        checker.feed(value or "")
        checker.close()
    except Exception as exc:  # noqa: BLE001 — парсер не должен ронять сохранение настроек
        return f"не удалось разобрать разметку: {exc}"
    if checker.error:
        return checker.error
    if checker.stack:
        return f"не закрыт тег <{checker.stack[-1]}>"
    return None


def validate(key: str, value: str) -> Optional[str]:
    """Проверка значения перед сохранением. None — всё в порядке."""
    if key in _T and not str(value or "").strip():
        return "текст не может быть пустым"
    if is_html(key):
        return validate_html(str(value or ""))
    return None


def plain(text: str) -> str:
    """Текст для всплывающего окна Telegram: там разметка не работает, теги убираем."""
    return html.unescape(re.sub(r"</?[a-zA-Z][^>]*>", "", text or ""))


# ------------------------------------------------------------------ выдача текста
async def t(key: str, user=None, missing_channels: Optional[list] = None, **values) -> str:
    """Текст из настроек с подставленными переменными. Пустое значение = текст по умолчанию.

    Значения, пришедшие от пользователей (имена, комментарии), экранирует вызывающий код.
    """
    from app import db, services  # локально: db сам импортирует этот модуль

    template = await db.get_setting(key)
    if not (template or "").strip() and key in _T:
        template = _T[key][1]
    if is_plain(key):
        user = None
    return await services.render(template, user, missing_channels, **values)
